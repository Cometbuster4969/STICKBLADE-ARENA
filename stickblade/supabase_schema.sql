-- Promote the elo PK across three milestones:
--   original:  (model, sharp)
--   Tier-S #1: (model, sharp, weapon)
--   Tier-S #2: (model, sharp, weapon, mode, arena)
--   Tier-S #3: (model, sharp, weapon, mode, arena, blindfolded)  ← this
-- Detect the current PK shape by checking whether blindfolded is among
-- the PK columns. If missing, drop and add the full 6-key composite.
-- Idempotent: safe to re-run.
do $$
declare
  has_full_pk boolean;
begin
  select
    bool_or(a.attname = 'blindfolded')
  into has_full_pk
  from   pg_index i
  join   pg_attribute a
         on a.attrelid = i.indrelid and a.attnum = any(i.indkey)
  where  i.indrelid = 'public.elo'::regclass
  and    i.indisprimary;

  if not coalesce(has_full_pk, false) then
    -- drop whatever the old PK was — any of the earlier shapes
    alter table elo drop constraint if exists elo_pkey;
    alter table elo add primary key
      (model, sharp, weapon, mode, arena, blindfolded);
  end if;
end$$;

