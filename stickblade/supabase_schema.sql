-- ============================================================================
-- 1. CREATE TABLES (no-op on existing tables, full schema on fresh installs)
-- ============================================================================
create table if not exists matches (
    id          text primary key,
    created     double precision,
    model_a     text,
    model_b     text,
    sharp       text,
    weapon      text default 'sword',     -- sword | dagger | spear | flail | bow
    -- Tier-S commit 2: mode + arena are part of the eval axis. Different
    -- control regime (macro vs joint) and different physics (normal / ice /
    -- low_gravity) = different rating cell. Persisted per-match so votes
    -- route to the right (model, sharp, weapon, mode, arena) elo row.
    mode        text default 'macro',     -- macro | joint
    arena       text default 'normal',    -- normal | ice | low_gravity
    -- Tier-S commit 3: blindfolded variant. When true, build_state()
    -- strips derived spatial hints (categorical enemy_is /
    -- enemy_height_relative / facing_enemy) so the model must reason
    -- from raw torso/head coords. Separate rating cell.
    blindfolded boolean default false,
    status      text,                     -- queued | running | done | error
    winner_side text,                     -- a | b | draw (CANVAS side: a=green, b=blue)
    method      text,
    turns       integer,
    error       text,
    blind       boolean default true,
    voted       boolean default false,
    -- True = the user's model_a was rendered as the BLUE (Fighter B) ragdoll.
    flip        boolean default false,
    -- 2-sentence post-fight commentary/roast generated by a 3rd LLM
    commentary  text,
    -- Tier-S commit 3: proxy metrics computed at finish_match() from
    -- the replay event stream. Powers /api/leaderboard/objective.
    -- All NULL if the replay predates Tier S #3 or was malformed.
    damage_dealt_a    double precision,
    damage_dealt_b    double precision,
    hits_landed_a     integer,
    hits_landed_b     integer,
    hits_attempted_a  integer,
    hits_attempted_b  integer,
    fallback_turns_a  integer,
    fallback_turns_b  integer,
    avg_distance      double precision
);

create table if not exists votes (
    id        text primary key,
    match_id  text references matches(id),
    created   double precision,
    choice    text                          -- a | b | draw (CANVAS side)
);

-- Per-cell Elo leaderboards. PK is
--   (model, sharp, weapon, mode, arena, blindfolded)
-- See AGENTS.md §10.5 ELO CELL KEY changelog for the full progression.
-- On fresh installs this creates the correct PK directly; on existing
-- deployments the migration block below promotes the PK safely.
create table if not exists elo (
    model       text,
    sharp       text,
    weapon      text default 'sword',
    mode        text default 'macro',    -- macro | joint
    arena       text default 'normal',   -- normal | ice | low_gravity
    blindfolded boolean default false,   -- Tier-S #3
    rating      double precision default 1000,
    wins        integer default 0,
    losses      integer default 0,
    draws       integer default 0,
    primary key (model, sharp, weapon, mode, arena, blindfolded)
);

create table if not exists tournaments (
    id            text primary key,
    created       double precision,
    name          text,
    size          integer,
    weapon        text default 'sword',
    sharp         text,
    arena         text default 'normal',
    mode          text default 'macro',
    status        text,                 -- queued | running | done | error
    current_round integer default 0,
    winner_model  text,
    models        text,                 -- JSON array of model ids in seed order
    error         text
);

create table if not exists tournament_matches (
    id            serial primary key,
    tournament_id text references tournaments(id),
    round         integer,
    slot          integer,
    match_id      text,
    model_a       text,
    model_b       text,
    winner_model  text,
    unique (tournament_id, round, slot)
);

